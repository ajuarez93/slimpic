// Bundles the worker entry into a string module so the library ships its worker inline
// (no CDN request, no bundler configuration for users).
import { build } from 'esbuild'
import { mkdirSync, writeFileSync } from 'node:fs'

const out = await build({
  entryPoints: ['src/core/worker-entry.ts'],
  bundle: true,
  write: false,
  format: 'iife',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
})
mkdirSync('src/generated', { recursive: true })
const code = out.outputFiles[0].text
writeFileSync('src/generated/worker-source.ts', `// Generated by scripts/build-worker.mjs. Do not edit.\nexport const workerSource = ${JSON.stringify(code)}\n`)
console.log(`worker: ${(code.length / 1024).toFixed(1)} KB`)
